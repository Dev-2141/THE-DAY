/**
 * Release signing. The key never enters the project: put its details in
 * src-tauri/gen/android/keystore.properties (ignored by git), or in the
 * environment variables THE_DAY_STORE_FILE, THE_DAY_STORE_PASSWORD,
 * THE_DAY_KEY_ALIAS and THE_DAY_KEY_PASSWORD. Without them the release
 * build is unsigned.
 *
 *   storeFile=C:/Users/you/keys/the-day-upload.jks
 *   keyAlias=upload
 *   storePassword=...   (or THE_DAY_STORE_PASSWORD)
 *   keyPassword=...     (or THE_DAY_KEY_PASSWORD)
 */
val keystoreProperties = Properties().apply {
    val propFile = rootProject.file("keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

fun signingValue(name: String): String? =
    System.getenv("THE_DAY_" + name.replace(Regex("([a-z])([A-Z])"), "$1_$2").uppercase())
        ?: keystoreProperties.getProperty(name)

